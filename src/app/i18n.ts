export type Key = keyof typeof dict

export function t(lang: Lang, key: Key): string {
  return dict[key][lang]
}

export function statusLabel(lang: Lang, s: RequestStatus): string {
  return dict[`status_${s}` as Key][lang]
}

export function fmtDate(lang: Lang, iso: string): string {
  const d = new Date(iso.length === 10 ? iso + 'T00:00:00' : iso)
  return d.toLocaleDateString(lang === 'th' ? 'th-TH' : 'en-GB', { day: 'numeric', month: 'short', year: lang === 'th' ? '2-digit' : undefined })
}

export function fmtTime(lang: Lang, iso: string): string {
  return new Date(iso).toLocaleTimeString(lang === 'th' ? 'th-TH' : 'en-GB', { hour: '2-digit', minute: '2-digit' })
}
